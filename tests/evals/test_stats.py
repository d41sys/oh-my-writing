def make_run(root: Path, text: str | None, *, error=None, rep=1, condition="skill"):
    cid = "structured-drafting/tiny-email-no-scaffolding"
    d = root / "runs" / f"{cid.replace('/', '__')}__omp__{condition}__r{rep}"
    (d / "workspace" / "out").mkdir(parents=True, exist_ok=True)
    (d / "meta.json").write_text(json.dumps({"case": cid, "skill": "structured-drafting", "host": "omp", "condition": condition,
                                             "rep": rep, "skill_loaded": condition == "skill", "exit_code": 0, "error": error,
                                             "duration_s": 1}))
    (d / "reply.md").write_text("done")
    if text is not None:
        (d / "workspace" / "out" / "email.md").write_text(text)
    (root / "run.json").write_text(json.dumps({"id": root.name, "hosts": ["omp"], "repeat": 1}))


