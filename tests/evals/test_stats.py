def test_sentence_stats_exact():
    text = "The cat sat on the mat. The dog ran to the car. A bird sang in the tree."
    s = stats.sentence_stats(text)
    assert (s["n"], s["mean"], s["cv"]) == (3, 6.0, 0.0)
    assert s["flesch"] == pytest.approx(206.835 - 1.015 * 6 - 84.6 * 1)


def test_sentence_stats_cv_and_threshold():
    text = "One two. One two three four five six. One two three four."  # lengths 2, 6, 4
    s = stats.sentence_stats(text)
    assert s["mean"] == 4.0
    assert s["cv"] == pytest.approx((8 / 3) ** 0.5 / 4)
    assert stats.sentence_stats("Only one sentence here.")["cv"] is None  # fewer than 3 sentences
    assert stats.sentence_stats("Only one sentence here.")["n"] == 1


def test_sentence_stats_skip_lists_headings_and_code():
    text = "# Title\n\n- a bullet item here\n- another bullet item\n\n```\nnot prose at all. really.\n```\n\nOne two. Three four. Five six."
    assert stats.sentence_stats(text)["n"] == 3


def test_headings_ignore_code_and_count_levels():
    text = "# A\n\ntext\n\n## B\n\n```\n# not a heading\n```\n\n#nospace\n"
    assert stats.headings(text) == 2


def test_list_line_ratio():
    text = "# Heading\n\nIntro line.\n- one\n- two\n1. three\n```\n- code\n```\nlast line"
    assert stats.list_line_ratio(text) == pytest.approx(3 / 5)  # 3 list lines of intro, 3 items, last
    assert stats.list_line_ratio("# only a heading") is None


def test_repeated_sentences():
    same = "The migration finished on Tuesday without any data loss. Something else entirely happened afterwards in the office. " \
           "The migration finished on Tuesday without any data loss."
    assert stats.repeated_sentences(same) == 1
    near = "The migration finished on Tuesday without any data loss at all. The migration finished on Tuesday without any data loss."
    assert stats.repeated_sentences(near) == 1
    distinct = "The migration finished on Tuesday. Customers saw nothing unusual during the cutover window."
    assert stats.repeated_sentences(distinct) == 0
    assert stats.repeated_sentences("Short one. Short one. Short one.") == 0  # under 6 words never counts


def test_hedge_count_whole_words():
    assert stats.hedge_count("It may work, and it might not. Mayor Perhaps could.") == 4  # may, might, perhaps, could
    assert stats.hedge_count("The mayor spoke.") == 0
    assert stats.hedge_count("That said, it is worth noting the risk.") == 2


def test_stock_phrase_count():
    assert stats.stock_phrase_count("In today's fast-paced world we delve into a seamless, game-changing tool.") == 4
    assert stats.stock_phrase_count("The estimator is robust to outliers.") == 0  # literal senses are not stock phrases


def test_placeholder_count_and_source_exemption():
    text = "Hi,\n\nSee [VERIFY: the date]. Best,\n[Your name]\n{{first_name}} TBD"
    assert stats.placeholder_count(text) == 4
    assert stats.placeholder_count(text, sources="owner: TBD for now") == 3  # TBD is in the sources
    assert stats.placeholder_count("Run `cmd --name [Your name]` then:\n```\n[TODO]\n```") == 0  # code is not prose
    assert stats.placeholder_count("A [1] citation and [ASK AUTHOR: who?] and [UNTESTED on Windows]") == 2


def test_process_talk_count():
    assert stats.process_talk_count("I rewrote the draft. As an AI I cannot. Here is the revised version.") == 3
    assert stats.process_talk_count("After the outage I changed the order of deploys.") == 0  # narrative, not meta-talk
    assert stats.process_talk_count("This report was generated by a tool.") == 1
    assert stats.process_talk_count("I ran the rollback.", sources="i ran the rollback") == 0


