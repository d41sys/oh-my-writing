VALUES = [0.3, -0.1, 0.5, 0.2, 0.0, 0.4, -0.2, 0.6]


def test_bootstrap_ci_is_deterministic_and_sane():
    a = stats.bootstrap_ci(VALUES, "x")
    assert a == stats.bootstrap_ci(list(VALUES), "x")
    assert a != stats.bootstrap_ci(VALUES, "y")  # the label seeds the generator
    mean = sum(VALUES) / len(VALUES)
    assert min(VALUES) <= a[0] < mean < a[1] <= max(VALUES)
    assert stats.bootstrap_ci([0.2, 0.2, 0.2], "x") == pytest.approx((0.2, 0.2))
    assert stats.bootstrap_ci([1.0], "x") is None


def test_bootstrap_ci_does_not_depend_on_hash_seed():
    code = ("import sys; sys.path.insert(0, %r); import stats; print(stats.bootstrap_ci(%r, 'x'))" % (str(EVALS), VALUES))
    outs = {subprocess.run([sys.executable, "-B", "-c", code], capture_output=True, text=True, check=True,
                           env={**os.environ, "PYTHONHASHSEED": seed}).stdout for seed in ("1", "2", "random")}
    assert len(outs) == 1


def test_sign_test_p():
    assert stats.sign_test_p([1, 1, 1, 1, 1]) == pytest.approx(2 / 32)
    assert stats.sign_test_p([1, 1, 1, 1, 1, -1]) == pytest.approx(2 * 7 / 64)
    assert stats.sign_test_p([1, -1]) == 1.0
    assert stats.sign_test_p([0, 0]) is None and stats.sign_test_p([]) is None


def test_paired_averages_repetitions_per_case():
    a = {("h", "c1", 1): 1.0, ("h", "c1", 2): 3.0, ("h", "c2", 1): 5.0, ("h", "c3", 1): 2.0}
    b = {("h", "c1", 1): 2.0, ("h", "c1", 2): 6.0, ("h", "c2", 1): 5.0, ("h", "c4", 1): 9.0}  # c3 and c4 are unpaired
    p = stats.paired(a, b, "t")
    assert (p["n_pairs"], p["n_cases"]) == (3, 2)
    assert p["per_case"] == {"h|c1": 2.0, "h|c2": 0.0}
    assert p["diff"] == 1.0 and p["a_mean"] == 3.5 and p["b_mean"] == 4.5
    assert stats.paired({}, b, "t")["diff"] is None


def test_verdict():
    assert stats.verdict(0.5, (0.1, 0.9), "lower", 10) == "worse"
    assert stats.verdict(0.5, (0.1, 0.9), "higher", 10) == "better"
    assert stats.verdict(-0.5, (-0.9, -0.1), "lower", 10) == "better"
    assert stats.verdict(0.1, (-0.1, 0.3), "lower", 10) == "same"
    assert stats.verdict(0.5, (0.1, 0.9), None, 10) == "info"
    assert stats.verdict(0.5, (0.1, 0.9), "lower", 2) == "few"
    assert stats.verdict(None, None, "lower", 10) == "n/a"


def rec(case_id, skill, cond, rep, loaded=True, **metrics):
    base = dict.fromkeys(stats.METRICS)
    base.update(metrics)
    return {"case": case_id, "skill": skill, "kind": "reader", "host": "h", "condition": cond, "rep": rep,
            "host_error": False, "skill_loaded": loaded, "metrics": base}


def test_aggregate_pairs_conditions_and_skips_host_errors():
    records = []
    for i in range(6):
        records += [rec(f"s/c{i}", "s", "baseline", 1, slop_per_1000w=4.0 + i), rec(f"s/c{i}", "s", "skill", 1, slop_per_1000w=1.0 + i)]
    records[0]["host_error"] = True  # c0 baseline crashed: that pair drops out
    agg = stats.aggregate(records)
    d = agg["skill_minus_baseline"]["h/ALL/skill"]["slop_per_1000w"]
    assert d["n_cases"] == 5 and d["diff"] == -3.0 and d["verdict"] == "better"
    assert agg["describe"]["h/ALL/baseline"]["slop_per_1000w"]["n_cases"] == 5


def test_compare_runs_flags_worse_with_ci():
    a = [rec(f"s/c{i}", "s", "skill", 1, hedge_per_1000w=2.0 + 0.1 * i) for i in range(8)]
    b = [rec(f"s/c{i}", "s", "skill", 1, hedge_per_1000w=3.0 + 0.1 * i) for i in range(8)]
    cmp = stats.compare_runs(a, b, "skill")
    d = cmp["h/ALL"]["hedge_per_1000w"]
    assert d["diff"] == pytest.approx(1.0) and d["verdict"] == "worse" and d["p"] == pytest.approx(2 / 256)
    assert cmp["h/ALL"]["words"]["verdict"] == "n/a" or cmp["h/ALL"]["words"]["n_pairs"] == 0
    assert stats.compare_runs(a, b, "baseline")["h/ALL"]["hedge_per_1000w"]["n_pairs"] == 0


# ---------------------------------------------------------------- skill minus competitor

def competitor_records():
    """Six cases x two reps for the skill; competitor x ran cases 0-4 (not 5), and never loaded its skill on case 4."""
    recs = []
    for i in range(6):
        for rep in (1, 2):
            recs.append(rec(f"s/c{i}", "s", "skill", rep, slop_per_1000w=1.0 + 0.1 * i, words=100.0))
            if i < 5:
                recs.append(rec(f"s/c{i}", "s", "competitor-x", rep, loaded=i != 4, slop_per_1000w=3.0 + 0.1 * i, words=100.0))
    recs.append(rec("s/c0", "s", "baseline", 1, slop_per_1000w=9.0))  # other conditions never enter
    return recs


def test_skill_minus_competitor_pairs_on_host_case_rep_and_is_signed_skill_minus_competitor():
    d = stats.skill_minus_competitor(competitor_records())["h/x/ALL"]["slop_per_1000w"]
    assert (d["n_pairs"], d["n_cases"]) == (10, 5)  # the case the competitor skipped drops out
    assert d["diff"] == pytest.approx(-2.0) and d["b_mean"] == pytest.approx(1.2) and d["a_mean"] == pytest.approx(3.2)
    assert d["verdict"] == "better"  # lower slop is better, and the skill is lower
    assert "h/x/s" in stats.skill_minus_competitor(competitor_records())  # per skill as well as ALL


def test_skill_minus_competitor_loaded_only_drops_unloaded_pairs_on_either_side():
    recs = competitor_records()
    loaded = stats.skill_minus_competitor(recs, loaded_only=True)["h/x/ALL"]["slop_per_1000w"]
    assert (loaded["n_pairs"], loaded["n_cases"]) == (8, 4)  # case 4: the competitor never loaded
    for r in recs:
        if r["condition"] == "skill" and r["case"] == "s/c0" and r["rep"] == 2:
            r["skill_loaded"] = False  # ours did not load either: that pair drops out too
    loaded = stats.skill_minus_competitor(recs, loaded_only=True)["h/x/ALL"]["slop_per_1000w"]
    assert (loaded["n_pairs"], loaded["n_cases"]) == (7, 4)
    assert stats.skill_minus_competitor(recs)["h/x/ALL"]["slop_per_1000w"]["n_pairs"] == 10  # unfiltered keeps all
    recs[1]["host_error"] = True
    assert stats.skill_minus_competitor(recs)["h/x/ALL"]["slop_per_1000w"]["n_pairs"] == 9


